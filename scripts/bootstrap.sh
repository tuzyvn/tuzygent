#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TUZYGENT_HOME="${TUZYGENT_HOME:-$HOME/.tuzygent}"
MISE_INSTALLS="${MISE_INSTALLS:-$HOME/.local/share/mise/installs}"

find_bin() {
  for candidate in "$@"; do
    if [[ -n "$candidate" && -x "$candidate" ]]; then
      printf '%s\n' "$candidate"
      return 0
    fi
    if [[ -n "$candidate" ]] && command -v "$candidate" >/dev/null 2>&1; then
      command -v "$candidate"
      return 0
    fi
  done
  return 1
}

echo "==> 1. Checking tuzygent CLI & sandbox dependencies"
AGENT_CTL_BIN="$(find_bin agent-ctl "$HOME/.cargo/bin/agent-ctl" "$ROOT_DIR/target/release/agent-ctl" || true)"
BWRAP_BIN="$(find_bin bwrap || true)"
NODE_BIN="$(find_bin node || true)"
echo "  agent-ctl:   ${AGENT_CTL_BIN:-MISSING (install with: cargo install --path crates/agent-cli)}"
echo "  bubblewrap:  ${BWRAP_BIN:-not found (will fallback to host)}"
echo "  node:        ${NODE_BIN:-not found}"

echo ""
echo "==> 2. Detecting AI CLI binaries (PATH + mise)"
AGY_DETECTED="$(find_bin \
  "${AGY_BIN:-}" \
  agy \
  antigravity \
  "$MISE_INSTALLS/antigravity-cli/latest/antigravity" \
  "$MISE_INSTALLS/antigravity-cli/latest/agy" \
  "$MISE_INSTALLS/antigravity-cli/latest/bin/agy" || true)"

CLAUDE_DETECTED="$(find_bin \
  claude \
  "$MISE_INSTALLS/claude/latest/claude" \
  "$MISE_INSTALLS/claude/latest/bin/claude" || true)"

CODEX_DETECTED="$(find_bin \
  "${CODEX_BIN:-}" \
  codex \
  "$MISE_INSTALLS/codex/latest/bin/codex" \
  "$MISE_INSTALLS/codex/latest/codex" || true)"

OLLAMA_DETECTED="$(find_bin ollama || true)"

echo "  antigravity: ${AGY_DETECTED:-not found}"
echo "  claude:      ${CLAUDE_DETECTED:-not found}"
echo "  codex:       ${CODEX_DETECTED:-not found}"
echo "  ollama:      ${OLLAMA_DETECTED:-not found}"

mkdir -p "$TUZYGENT_HOME"

ENGINES_TOML="$TUZYGENT_HOME/engines.toml"
if [[ -f "$ENGINES_TOML" ]]; then
  cp "$ENGINES_TOML" "$ENGINES_TOML.bak.$(date +%Y%m%d%H%M%S)"
fi

DEFAULT_ENGINE="fast_echo"
if [[ -n "$AGY_DETECTED" ]]; then
  DEFAULT_ENGINE="antigravity"
elif [[ -n "$CODEX_DETECTED" ]]; then
  DEFAULT_ENGINE="codex"
elif [[ -n "$CLAUDE_DETECTED" ]]; then
  DEFAULT_ENGINE="claude"
elif [[ -n "$OLLAMA_DETECTED" ]]; then
  DEFAULT_ENGINE="stackpilot_ollama"
fi

SANDBOX_DRIVER="host"
if [[ -n "$BWRAP_BIN" ]]; then
  SANDBOX_DRIVER="bubblewrap"
fi

{
  echo "# Auto-generated by tuzygent/scripts/bootstrap.sh on $(date -Iseconds)"
  echo "[defaults]"
  echo "engine = \"$DEFAULT_ENGINE\""
  echo "timeout_seconds = 600"
  echo "sandbox_driver = \"$SANDBOX_DRIVER\""
  echo ""
  echo "[security]"
  echo "allowed_env_vars = ["
  echo "    \"CODEX_API_KEY\","
  echo "    \"CODEX_BIN\","
  echo "    \"ANTHROPIC_API_KEY\","
  echo "    \"GEMINI_API_KEY\","
  echo "    \"OPENAI_API_KEY\","
  echo "    \"ANTIGRAVITY_API_KEY\","
  echo "    \"AGY_BIN\","
  echo "    \"OLLAMA_HOST\","
  echo "    \"OTEL_EXPORTER_OTLP_ENDPOINT\","
  echo "    \"STACKPILOT_URL\","
  echo "    \"STACKPILOT_TOKEN\""
  echo "]"
  echo "mount_credentials = ["
  echo "    { source = \"~/.codex/auth.json\", target = \"/root/.codex/auth.json\", readonly = true },"
  echo "    { source = \"~/.gemini\", target = \"/root/.gemini\", readonly = true },"
  echo "    { source = \"~/.claude\", target = \"/root/.claude\", readonly = true }"
  echo "]"

  if [[ -n "$AGY_DETECTED" ]]; then
    echo ""
    echo "[engines.antigravity]"
    echo "kind = \"antigravity\""
    echo "binary_path = \"$AGY_DETECTED\""
    echo "args = [\"--interactive=false\", \"--output-format\", \"stream-json\", \"--message\", \"{prompt}\"]"
    echo "interactive_fallback = \"tmux\""
  fi

  if [[ -n "$CLAUDE_DETECTED" ]]; then
    echo ""
    echo "[engines.claude]"
    echo "kind = \"claude_code\""
    echo "binary_path = \"$CLAUDE_DETECTED\""
    echo "args = [\"-p\", \"{prompt}\", \"--output-format\", \"json\"]"
    echo "interactive_fallback = \"tmux\""
  fi

  if [[ -n "$CODEX_DETECTED" ]]; then
    echo ""
    echo "[engines.codex]"
    echo "kind = \"codex\""
    echo "binary_path = \"$CODEX_DETECTED\""
    echo "output_parser = \"codex_jsonl\""
  fi

  if [[ -n "$OLLAMA_DETECTED" ]]; then
    echo ""
    echo "[engines.stackpilot_ollama]"
    echo "kind = \"generic\""
    echo "binary_path = \"$OLLAMA_DETECTED\""
    echo "args = [\"run\", \"qwen2.5-coder:7b\", \"{prompt}\"]"
    echo "output_parser = \"raw\""
  fi
} > "$ENGINES_TOML"

echo ""
echo "==> 3. Wrote OS-wide engine config: $ENGINES_TOML (default=$DEFAULT_ENGINE, sandbox=$SANDBOX_DRIVER)"

if [[ -n "${STACKPILOT_MCP:-}" && -f "$STACKPILOT_MCP" ]]; then
  MCP_JSON="$TUZYGENT_HOME/stackpilot-mcp.json"
  cat > "$MCP_JSON" <<EOF
{
  "mcpServers": {
    "stackpilot": {
      "command": "node",
      "args": ["$STACKPILOT_MCP"]
    }
  }
}
EOF
  echo "==> 4. Wrote StackPilot MCP config: $MCP_JSON"
fi

if [[ -n "$AGENT_CTL_BIN" ]]; then
  echo ""
  echo "==> 5. Verifying tuzygent engine & rig status"
  "$AGENT_CTL_BIN" engines --workspace "$ROOT_DIR"
  "$AGENT_CTL_BIN" rig status
fi
